func TestLoad_InvalidYAML(t *testing.T) {
	f, err := os.CreateTemp("", "keel-bad-*.yaml")
	if err != nil {
		t.Fatal(err)
	}
	defer os.Remove(f.Name())
	_, _ = f.WriteString(":\t bad yaml {{{\n")
	f.Close()

	_, err = config.Load(f.Name(), "")
	if err == nil {
		t.Fatal("expected error for invalid YAML")
	}
}

