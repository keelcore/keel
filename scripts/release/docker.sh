#!/usr/bin/env bash
# docker.sh
# Build, tag, push, and sign multi-arch container images (linux/amd64 and
# linux/arm64) for each variant in config/release-images.local.txt. Uses pre-built binaries from dist/
# (dist/<project>-<variant>-linux-<arch>) — build-once, package-once. scripts/release/docker.local.sh, if
# any, runs first. The Dockerfile: config/release-dockerfile.local.txt.
#
# docker runs on the host; syft, grype and cosign run in the dev image
# (scripts/dev/run.sh) on the files they read and write here.
#
# Flavors and their architectures run concurrently (scripts/lib/parallel.sh).
#
# Per flavor and architecture: build → SBOM from the local image + grype scan
# (fail on fixable HIGH/CRITICAL) → push the arch tag → sign + attest that SBOM
# by digest. Then per flavor: assemble the multi-arch index under the primary
# tag → sign it → attest the OpenVEX document to it → record its digest in
# $GITHUB_OUTPUT → move aliases (the primary variant only). Aliases move last, so a failure
# never leaves vX.Y / vX / latest on an unsigned image.
#
# Image metadata is reproducible: org.opencontainers.image.created and
# SOURCE_DATE_EPOCH come from the commit time (UTC), never the wall clock.
#
# Required environment variables:
#   GITHUB_TOKEN   — GHCR write token (GITHUB_TOKEN in Actions)
#   GITHUB_ACTOR   — registry username (github.actor in Actions)
#
# Image targets (each a linux/amd64 + linux/arm64 index): ghcr.io/<repo>:<tag><suffix>, and vX.Y, vX
# and latest for the primary variant. Per-arch images behind each index: <primary tag>-amd64, -arm64.

# bash configuration:
# 1) Exit script if you try to use an uninitialized variable.
set -o nounset

# 2) Exit script if a statement returns a non-true return value.
set -o errexit

# 3) Use the error status of the first failure, rather than that of the last item in a pipeline.
set -o pipefail

# 4) Keep errexit on inside command substitutions, so a failed push cannot hand back a digest.
shopt -s inherit_errexit

# shellcheck source=../lib/parallel.sh
source "$(dirname "${BASH_SOURCE[0]}")/../lib/parallel.sh"
# shellcheck source=../lib/tool-config.sh
source "$(dirname "${BASH_SOURCE[0]}")/../lib/tool-config.sh"

readonly REGISTRY='ghcr.io'
IMAGE="${REGISTRY}/$(release_repo)"
readonly IMAGE
DOCKERFILE="$(config_replace release-dockerfile)"
readonly DOCKERFILE
PROJECT="$(project_name)"
readonly PROJECT
readonly LOCAL_HOOK='scripts/release/docker.local.sh'
readonly DIST='dist'
readonly TARGET='target'
# grype's vulnerability database, kept across its dev-image runs (target/ is writable there).
export GRYPE_DB_CACHE_DIR="${TARGET}/grype-db"
export KEELCORE_DEV_ENV="${KEELCORE_DEV_ENV:-} GRYPE_DB_CACHE_DIR GRYPE_DB_AUTO_UPDATE"
readonly ARCHES='amd64 arm64'
readonly VEX_DOCUMENT="${DIST}/${PROJECT}.openvex.json"  # generated by scripts/release/vex.sh
readonly SBOM_PREDICATE='https://spdx.dev/Document'
# Identity of a signature made by this repo's release workflow (keyless, GitHub OIDC).
readonly -a VERIFY_IDENTITY=(
  --certificate-identity-regexp "$(release_identity)"
  --certificate-oidc-issuer 'https://token.actions.githubusercontent.com'
)

function main() {
  exec 5>&1
  validate_args "${@:-}"
  if [ -z "$(release_variants)" ]; then
    log 'ℹ️  No images configured; nothing to publish'
    return 0
  fi
  local tag
  tag="$(resolve_tag)"
  log "Publishing container images for ${tag}"
  require_env
  require_docker
  registry_login
  [ ! -f "${LOCAL_HOOK}" ] || bash "${LOCAL_HOOK}"
  update_grype_db
  local -a variants
  read -r -a variants <<< "$(release_variants | cut -f1 | paste -sd' ' -)"
  run_parallel publish_flavor "${variants[@]}" -- "${tag}"
  log "All container images published and signed"
}

function log() {
  local -r msg="${1:-}"
  printf '%s\n' "${msg}" | tee -a '/tmp/docker.log' >&5
}

function validate_args() { :; }

# update_grype_db fetches the vulnerability database once, up front: concurrent scans share its
# directory, so they only read it.
function update_grype_db() {
  log "Updating the grype database"
  bash scripts/dev/run.sh grype db update >&5
  export GRYPE_DB_AUTO_UPDATE=false
}

function require_env() {
  local missing=0
  for var in GITHUB_TOKEN GITHUB_ACTOR; do
    if [ -z "${!var:-}" ]; then
      log "ERROR: ${var} is required"
      missing=1
    fi
  done
  [ "${missing}" -eq 0 ] || exit 1
}

function require_docker() {
  if ! command -v docker >/dev/null 2>&1; then
    log "ERROR: docker not found in PATH"
    exit 1
  fi
}

function registry_login() {
  log "Logging in to ${REGISTRY}"
  printf '%s' "${GITHUB_TOKEN}" | \
    docker login "${REGISTRY}" --username "${GITHUB_ACTOR}" --password-stdin
}

# resolve_tag echoes a v* tag or synthesizes one from git describe.
function resolve_tag() {
  git describe --tags --dirty --always
}

# semver_minor echoes the vMAJOR.MINOR portion of a version tag.
function semver_minor() {
  printf '%s' "${1}" | grep -oE '^v[0-9]+\.[0-9]+'
}

# semver_major echoes the vMAJOR portion of a version tag.
function semver_major() {
  printf '%s' "${1}" | grep -oE '^v[0-9]+'
}

# publish_flavor builds, scans, pushes and signs each arch image, then the index.
function publish_flavor() {
  local -r flavor="${1}"
  local -r tag="${2}"
  local -r primary_tag="$(primary_tag_for "${flavor}" "${tag}")"
  local digests
  digests="$(mktemp -d)"
  local -a arches
  read -r -a arches <<< "${ARCHES}"
  run_parallel publish_arch "${arches[@]}" -- "${flavor}" "${tag}" "${primary_tag}" "${digests}"
  local -a arch_digests=()
  local arch
  for arch in "${arches[@]}"; do
    arch_digests+=("$(cat "${digests}/${arch}")")
  done
  rm -rf "${digests}"
  local index
  index="$(create_index "${primary_tag}" "${arch_digests[@]}")"
  sign_image "${index}"
  attest_predicate "${index}" "${VEX_DOCUMENT}" 'openvex'
  record_digest "${flavor}" "${index}"
  push_aliases "${flavor}" "${tag}" "${primary_tag}"
}

# publish_arch builds, scans, pushes, signs and attests one arch image and
# writes its digest reference (<image>@sha256:...) to DIGESTS/ARCH.
function publish_arch() {
  local -r arch="${1}"
  local -r flavor="${2}"
  local -r ref="${4}-${arch}"
  build_image "${flavor}" "${arch}" "${3}" "${ref}"
  scan_image "${ref}" "$(sbom_path "${flavor}" "${arch}")"
  local digest
  digest="$(push_image "${ref}")"
  sign_image "${digest}"
  attest_predicate "${digest}" "$(sbom_path "${flavor}" "${arch}")" "${SBOM_PREDICATE}"
  printf '%s\n' "${digest}" > "${5}/${arch}"
}

# variant_suffix VARIANT: its tag suffix; empty for the primary.
function variant_suffix() {
  release_variants | awk -F'\t' -v v="${1}" '$1 == v { print $2; exit }'
}

function primary_tag_for() {
  printf '%s' "${IMAGE}:${2}$(variant_suffix "${1}")"
}

function build_image() {
  local -r flavor="${1}"
  local -r arch="${2}"
  local -r tag="${3}"
  local -r ref="${4}"
  local -r binary="${DIST}/${PROJECT}-${flavor}-linux-${arch}"
  [ -f "${binary}" ] || { log "ERROR: binary not found: ${binary}"; exit 1; }
  local ctx epoch
  ctx="$(mktemp -d)"
  cp "${binary}" "${ctx}/${PROJECT}"
  epoch="$(git log -1 --format=%ct)"
  log "  Building ${ref} (flavor=${flavor}, linux/${arch})"
  # --provenance/--sbom off: this script attests its own SBOM and the workflow
  # attests SLSA provenance, so each pushed arch image stays a plain manifest.
  docker build \
    --platform "linux/${arch}" --provenance=false --sbom=false \
    --file "${DOCKERFILE}" \
    --build-arg "FLAVOR=${flavor}" \
    --build-arg "SOURCE_DATE_EPOCH=${epoch}" \
    --tag "${ref}" \
    --label "org.opencontainers.image.version=${tag}" \
    --label "org.opencontainers.image.created=$(utc_timestamp "${epoch}")" \
    --label "org.opencontainers.image.revision=$(git rev-parse HEAD)" \
    "${ctx}" >&5
  rm -rf "${ctx}"
}

# utc_timestamp formats epoch seconds as RFC 3339 UTC (GNU date, else BSD date).
function utc_timestamp() {
  local -r epoch="${1}"
  date -u -d "@${epoch}" +%Y-%m-%dT%H:%M:%SZ 2>/dev/null \
    || date -u -r "${epoch}" +%Y-%m-%dT%H:%M:%SZ
}

# scan_image writes the image's own SBOM from the local image and fails the
# release on any fixable HIGH or CRITICAL finding — before anything is pushed.
# syft and grype run in the dev image on the image archive (docker save).
function scan_image() {
  local -r ref="${1}"
  local -r sbom="${2}"
  local -r archive="${TARGET}/image-${ref##*:}.tar"
  log "  SBOM ${ref} → ${sbom}"
  mkdir -p "${TARGET}"
  docker save --output "${archive}" "${ref}"
  bash scripts/dev/run.sh syft scan "docker-archive:${archive}" --output "spdx-json=${sbom}" >&5
  rm -f "${archive}"
  log "  Scanning ${ref} (grype, fail on fixable high+)"
  bash scripts/dev/run.sh grype "sbom:${sbom}" --only-fixed --fail-on high >&5
}

function sbom_path() {
  printf '%s/sbom-%s-%s.spdx.json' "${DIST}" "${1}" "${2}"
}

# push_image pushes a tag and echoes its immutable digest reference.
function push_image() {
  local -r ref="${1}"
  log "  Pushing ${ref}"
  docker push "${ref}" >&5
  docker inspect --format='{{index .RepoDigests 0}}' "${ref}"
}

# create_index assembles the arch images into one index under the primary tag
# and echoes the index digest reference.
function create_index() {
  local -r primary_tag="${1}"
  shift
  log "  Creating index ${primary_tag} ($*)"
  docker buildx imagetools create --tag "${primary_tag}" "$@" >&5
  printf '%s@%s\n' "${IMAGE}" "$(index_digest "${primary_tag}")"
}

function index_digest() {
  docker buildx imagetools inspect "${1}" --format '{{json .Manifest}}' | jq -r '.digest'
}

# push_aliases points vX.Y, vX and latest at the already-signed primary index.
# Runs last, so a failed sign or scan never leaves an alias on an unsigned image.
function push_aliases() {
  local -r flavor="${1}"
  local -r tag="${2}"
  local -r primary_tag="${3}"
  [ -z "$(variant_suffix "${flavor}")" ] && [[ "${tag}" =~ ^v[0-9] ]] || return 0
  local alias
  for alias in "$(semver_minor "${tag}")" "$(semver_major "${tag}")" 'latest'; do
    log "  Pointing ${IMAGE}:${alias} at ${primary_tag}"
    docker buildx imagetools create --tag "${IMAGE}:${alias}" "${primary_tag}" >&5
  done
}

# record_digest exposes <flavor>_digest=sha256:... (the index) to later
# workflow steps (image provenance attestation, release verification).
function record_digest() {
  local -r flavor="${1}"
  local -r digest="${2}"
  [ -n "${GITHUB_OUTPUT:-}" ] || return 0
  printf '%s_digest=%s\n' "${flavor}" "${digest##*@}" >> "${GITHUB_OUTPUT}"
}

# cosign_run runs cosign in the dev image, logged in to GHCR (scripts/release/cosign.sh).
function cosign_run() {
  bash scripts/dev/run.sh bash scripts/release/cosign.sh "$@"
}

# sign_image is idempotent: a retry that hits Rekor 409 (entry already exists
# for this digest) succeeds when cosign verify confirms the existing signature.
function sign_image() {
  local -r digest="${1}"
  log "  Signing ${digest} (cosign keyless)"
  if cosign_run sign --yes "${digest}" >&5; then
    return 0
  fi
  log "  cosign sign failed; checking for an existing signature on ${digest}"
  cosign_run verify "${VERIFY_IDENTITY[@]}" "${digest}" >/dev/null
  log "  ✅ ${digest} already signed by this workflow"
}

# attest_predicate is idempotent in the same way as sign_image.
# SBOMs use the full SPDX predicate URI rather than the 'spdx' shortname:
# cosign v3.x shortname validation rejects syft SPDX 2.3 JSON; the URI form
# treats the predicate as an opaque JSON payload.
function attest_predicate() {
  local -r digest="${1}"
  local -r predicate="${2}"
  local -r type="${3}"
  log "  Attesting ${predicate} to ${digest}"
  if cosign_run attest --yes --predicate "${predicate}" --type "${type}" "${digest}" >&5; then
    return 0
  fi
  log "  cosign attest failed; checking for an existing ${type} attestation on ${digest}"
  cosign_run verify-attestation "${VERIFY_IDENTITY[@]}" --type "${type}" "${digest}" >/dev/null
  log "  ✅ ${digest} already carries this workflow's ${type} attestation"
}

main "${@:-}"
